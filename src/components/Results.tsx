import React, { useState } from 'react';
import { FaDownload, FaEye, FaFileAlt, FaStar, FaCheckCircle, FaTimesCircle } from 'react-icons/fa';
import './Results.css';

interface MatchResult {
  fileName: string;
  score: number;
  matchedSkills: string[];
  missingSkills: string[];
  feedback: string;
}

interface ResultsProps {
  results: MatchResult[];
  jobTitle: string;
}

const Results: React.FC<ResultsProps> = ({ results, jobTitle }) => {
  const [selectedResult, setSelectedResult] = useState<MatchResult | null>(null);

  const getScoreColor = (score: number) => {
    if (score >= 80) return 'var(--success)';
    if (score >= 60) return 'var(--warning)';
    return 'var(--error)';
  };

  const getScoreLabel = (score: number) => {
    if (score >= 80) return 'Excellent Match';
    if (score >= 60) return 'Good Match';
    return 'Needs Review';
  };

  const generateDetailedReport = (result: MatchResult) => {
    const analysisDate = new Date().toLocaleDateString();
    const skillsCoverage = Math.round((result.matchedSkills.length / (result.matchedSkills.length + result.missingSkills.length)) * 100);
    
    return `
TALENTMAP AI - COMPREHENSIVE RESUME ANALYSIS REPORT
==================================================

Job Position: ${jobTitle}
Candidate: ${result.fileName}
Analysis Date: ${analysisDate}
Overall Match Score: ${result.score}%
Recommendation: ${result.score >= 80 ? 'Highly Recommended for Interview' : result.score >= 60 ? 'Consider for Interview' : 'Not Recommended'}

SKILLS ANALYSIS SUMMARY:
========================
Skills Coverage: ${skillsCoverage}%
Matched Skills: ${result.matchedSkills.length}
Missing Skills: ${result.missingSkills.length}

MATCHED SKILLS (${result.matchedSkills.length}):
${result.matchedSkills.map(skill => `✓ ${skill}`).join('\n')}

MISSING/REQUIRED SKILLS (${result.missingSkills.length}):
${result.missingSkills.map(skill => `✗ ${skill}`).join('\n')}

DETAILED AI FEEDBACK:
====================
${result.feedback}

CANDIDATE EVALUATION METRICS:
=============================
• Technical Skills Alignment: ${skillsCoverage}%
• Experience Level Match: ${result.score >= 80 ? 'Excellent' : result.score >= 60 ? 'Good' : 'Needs Development'}
• Overall Compatibility: ${result.score >= 80 ? 'High' : result.score >= 60 ? 'Moderate' : 'Low'}

RECOMMENDATIONS FOR IMPROVEMENT:
===============================
${result.missingSkills.length > 0 ? 
  `• Priority Skills to Develop: ${result.missingSkills.slice(0, 3).join(', ')}
• Consider relevant certifications in these areas
• Highlight project experience demonstrating these skills
• Seek training or professional development opportunities` :
  `• Strong candidate profile with comprehensive skill match
• Consider for immediate interview scheduling
• Focus on behavioral and cultural fit assessment`}

INTERVIEWER NOTES:
=================
• Focus on validating claimed skills during technical assessment
• Probe deeper into experience with: ${result.matchedSkills.slice(0, 3).join(', ')}
${result.missingSkills.length > 0 ? `• Assess willingness and ability to learn: ${result.missingSkills.slice(0, 2).join(', ')}` : ''}
• Evaluate problem-solving approach and cultural alignment

==================================================
Generated by TalentMap AI | Powered by Umurava
Report generated on ${new Date().toLocaleString()}
    `.trim();
  };

  const downloadReport = (result: MatchResult) => {
    const reportContent = generateDetailedReport(result);
    const blob = new Blob([reportContent], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `TalentMap_Analysis_${result.fileName.replace(/\.[^/.]+$/, '')}_${new Date().toISOString().split('T')[0]}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const viewDetails = (result: MatchResult) => {
    setSelectedResult(result);
  };

  const closeModal = () => {
    setSelectedResult(null);
  };

  return (
    <section className="results section">
      <div className="container">
        <div className="section-header text-center">
          <h2>Analysis Results</h2>
          <p>Comprehensive AI-powered resume analysis for <strong>{jobTitle}</strong></p>
        </div>

        <div className="results-grid">
          {results.map((result, index) => (
            <div key={index} className="result-card card">
              <div className="result-header">
                <div className="file-info">
                  <h3 className="file-name">
                    <FaFileAlt size={16} style={{ marginRight: '8px', color: 'var(--primary-blue)' }} />
                    {result.fileName}
                  </h3>
                  <span 
                    className="score-label"
                    style={{ color: getScoreColor(result.score) }}
                  >
                    <FaStar size={12} style={{ marginRight: '4px' }} />
                    {getScoreLabel(result.score)}
                  </span>
                </div>
                <div 
                  className="score-circle"
                  style={{ '--score-color': getScoreColor(result.score) } as React.CSSProperties}
                >
                  <span className="score-value">{result.score}%</span>
                </div>
              </div>

              <div className="progress-section">
                <div className="progress-bar">
                  <div 
                    className="progress-fill"
                    style={{ 
                      width: `${result.score}%`,
                      background: getScoreColor(result.score)
                    }}
                  />
                </div>
              </div>

              <div className="skills-section">
                <div className="matched-skills">
                  <h4>
                    <FaCheckCircle size={14} style={{ marginRight: '6px', color: 'var(--success)' }} />
                    Matched Skills ({result.matchedSkills.length})
                  </h4>
                  <div className="skills-list">
                    {result.matchedSkills.slice(0, 4).map((skill, skillIndex) => (
                      <span key={skillIndex} className="skill-tag matched">
                        {skill}
                      </span>
                    ))}
                    {result.matchedSkills.length > 4 && (
                      <span className="skill-tag matched">+{result.matchedSkills.length - 4} more</span>
                    )}
                  </div>
                </div>

                {result.missingSkills.length > 0 && (
                  <div className="missing-skills">
                    <h4>
                      <FaTimesCircle size={14} style={{ marginRight: '6px', color: 'var(--error)' }} />
                      Missing Skills ({result.missingSkills.length})
                    </h4>
                    <div className="skills-list">
                      {result.missingSkills.slice(0, 3).map((skill, skillIndex) => (
                        <span key={skillIndex} className="skill-tag missing">
                          {skill}
                        </span>
                      ))}
                      {result.missingSkills.length > 3 && (
                        <span className="skill-tag missing">+{result.missingSkills.length - 3} more</span>
                      )}
                    </div>
                  </div>
                )}
              </div>

              <div className="feedback-section">
                <h4>AI Analysis Summary</h4>
                <p className="feedback-text">
                  {result.feedback.length > 150 ? `${result.feedback.substring(0, 150)}...` : result.feedback}
                </p>
              </div>

              <div className="result-actions">
                <button 
                  className="btn btn-secondary"
                  onClick={() => viewDetails(result)}
                >
                  <FaEye size={14} style={{ marginRight: '6px' }} />
                  View Details
                </button>
                <button 
                  className="btn btn-primary"
                  onClick={() => downloadReport(result)}
                >
                  <FaDownload size={14} style={{ marginRight: '6px' }} />
                  Download Report
                </button>
              </div>
            </div>
          ))}
        </div>

        <div className="results-summary">
          <h3>Analysis Summary</h3>
          <div className="summary-stats">
            <div className="stat-item">
              <span className="stat-value">{results.length}</span>
              <span className="stat-label">Resumes Analyzed</span>
            </div>
            <div className="stat-item">
              <span className="stat-value">
                {results.filter(r => r.score >= 80).length}
              </span>
              <span className="stat-label">Excellent Matches</span>
            </div>
            <div className="stat-item">
              <span className="stat-value">
                {Math.round(results.reduce((sum, r) => sum + r.score, 0) / results.length)}%
              </span>
              <span className="stat-label">Average Score</span>
            </div>
            <div className="stat-item">
              <span className="stat-value">
                {results.filter(r => r.score >= 60).length}
              </span>
              <span className="stat-label">Interview Ready</span>
            </div>
          </div>
        </div>

        {/* Detailed View Modal */}
        {selectedResult && (
          <div className="modal-overlay" onClick={closeModal}>
            <div className="modal-content" onClick={(e) => e.stopPropagation()}>
              <div className="modal-header">
                <h2>
                  <FaFileAlt size={20} style={{ marginRight: '8px' }} />
                  Detailed Analysis: {selectedResult.fileName}
                </h2>
                <button className="modal-close" onClick={closeModal}>×</button>
              </div>
              
              <div className="modal-body">
                <div className="detail-score-section">
                  <div className="detail-score">
                    <span className="detail-score-value">{selectedResult.score}%</span>
                    <span className="detail-score-label">Overall Match</span>
                  </div>
                  <div className="detail-recommendation">
                    <strong>Recommendation: </strong>
                    {selectedResult.score >= 80 ? '🟢 Highly Recommended for Interview' : 
                     selectedResult.score >= 60 ? '🟡 Consider for Interview' : '🔴 Not Recommended'}
                  </div>
                </div>

                <div className="detail-skills-section">
                  <div className="detail-matched">
                    <h4>
                      <FaCheckCircle size={16} style={{ marginRight: '8px', color: 'var(--success)' }} />
                      Matched Skills ({selectedResult.matchedSkills.length})
                    </h4>
                    <div className="skills-list">
                      {selectedResult.matchedSkills.map((skill, index) => (
                        <span key={index} className="skill-tag matched">{skill}</span>
                      ))}
                    </div>
                  </div>

                  {selectedResult.missingSkills.length > 0 && (
                    <div className="detail-missing">
                      <h4>
                        <FaTimesCircle size={16} style={{ marginRight: '8px', color: 'var(--error)' }} />
                        Missing Skills ({selectedResult.missingSkills.length})
                      </h4>
                      <div className="skills-list">
                        {selectedResult.missingSkills.map((skill, index) => (
                          <span key={index} className="skill-tag missing">{skill}</span>
                        ))}
                      </div>
                    </div>
                  )}
                </div>

                <div className="detail-feedback">
                  <h4>Complete AI Analysis</h4>
                  <p>{selectedResult.feedback}</p>
                </div>

                <div className="detail-metrics">
                  <h4>Analysis Metrics</h4>
                  <div className="metrics-grid">
                    <div className="metric">
                      <span className="metric-label">Skills Coverage</span>
                      <span className="metric-value">
                        {Math.round((selectedResult.matchedSkills.length / (selectedResult.matchedSkills.length + selectedResult.missingSkills.length)) * 100)}%
                      </span>
                    </div>
                    <div className="metric">
                      <span className="metric-label">Experience Match</span>
                      <span className="metric-value">
                        {selectedResult.score >= 80 ? 'Excellent' : selectedResult.score >= 60 ? 'Good' : 'Fair'}
                      </span>
                    </div>
                    <div className="metric">
                      <span className="metric-label">Interview Priority</span>
                      <span className="metric-value">
                        {selectedResult.score >= 80 ? 'High' : selectedResult.score >= 60 ? 'Medium' : 'Low'}
                      </span>
                    </div>
                  </div>
                </div>
              </div>

              <div className="modal-footer">
                <button 
                  className="btn btn-primary"
                  onClick={() => downloadReport(selectedResult)}
                >
                  <FaDownload size={14} style={{ marginRight: '8px' }} />
                  Download Full Report
                </button>
                <button className="btn btn-secondary" onClick={closeModal}>
                  Close
                </button>
              </div>
            </div>
          </div>
        )}
      </div>
    </section>
  );
};

export default Results;